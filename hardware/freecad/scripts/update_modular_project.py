#!/usr/bin/env python3
"""Refresh and validate modular pendant documents in an isolated FreeCAD worker.

Loads pendant-master.FCStd first, then each editable component document in
pendant-bodies/. Optionally includes an assembly candidate via --assembly.
Only documents that recompute and pass shape/reference checks are saved.
Each invocation has a bounded lifetime and owns its FreeCAD process group.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import signal
import subprocess
import tempfile

SCRIPT = Path(__file__).resolve()
FREECAD_DIR = SCRIPT.parents[1]
ROOT = next((p for p in SCRIPT.parents if (p / ".git").exists()), None)
if ROOT is None:
    raise SystemExit("Could not locate repository root from this script")

DEFAULT_CMD = Path("/Applications/FreeCAD.app/Contents/Resources/bin/freecadcmd")
COMPONENTS = (
    'breakout-board.FCStd',
    'display-retainer.FCStd',
    'faceplate-locators.FCStd',
    'usb-tethered-cover.FCStd',
)


def find_freecadcmd(override: str | None) -> str:
    if override:
        return override
    env_cmd = os.environ.get("FREECADCMD")
    if env_cmd:
        return env_cmd
    if DEFAULT_CMD.is_file():
        return str(DEFAULT_CMD)
    found = shutil.which("freecadcmd")
    if found:
        return found
    raise SystemExit("freecadcmd not found; set FREECADCMD to its executable path")


def make_macro(root: Path, assembly: Path | None) -> str:
    cfg = json.dumps({"root": str(root), "assembly": str(assembly) if assembly else None,
                      "components": COMPONENTS})
    return r'''# Generated by update_modular_project.py; do not edit this temporary macro.
import FreeCAD as App
import json, os, traceback
CFG = json.loads(@@CFG@@)
opened = []
results = []
errors = []

def open_doc(path):
    path = os.path.realpath(path)
    for d in App.listDocuments().values():
        if d.FileName and os.path.realpath(d.FileName) == path:
            return d
    d = App.openDocument(path)
    opened.append(d.Name)
    return d

def validate_and_save(path, kind):
    d = open_doc(path)
    refreshed_external_expressions = []
    if kind == 'assembly-candidate':
        for link in (o for o in d.Objects if o.TypeId == 'App::Link'):
            link.LinkPlacement = link.LinkedObject.Placement
    else:
        # External spreadsheet expressions can remain cached after reopening
        # the master with changed values. Touch and reassign them so FreeCAD
        # resolves their current source before recomputation.
        for obj in d.Objects:
            for expression_path, expression_text in getattr(obj, 'ExpressionEngine', []):
                if '#<<' in expression_text:
                    obj.touch()
                    obj.setExpression(expression_path, expression_text)
                    refreshed_external_expressions.append({'object': obj.Name,
                                                           'path': expression_path})
    d.recompute()
    if kind == 'assembly-candidate':
        links = [o for o in d.Objects if o.TypeId == 'App::Link']
        interim = [o for o in d.Objects if o.Name.startswith('Interim_')]
        link_report = []
        for link in links:
            target = link.LinkedObject
            shape, source_shape = link.Shape, target.Shape
            if (shape.isNull() or not shape.isValid() or source_shape.isNull()
                    or not source_shape.isValid()):
                raise RuntimeError('invalid assembly link/source: ' + link.Name)
            bbox = (shape.BoundBox.XMin, shape.BoundBox.XMax,
                    shape.BoundBox.YMin, shape.BoundBox.YMax,
                    shape.BoundBox.ZMin, shape.BoundBox.ZMax)
            source_bbox = (source_shape.BoundBox.XMin, source_shape.BoundBox.XMax,
                           source_shape.BoundBox.YMin, source_shape.BoundBox.YMax,
                           source_shape.BoundBox.ZMin, source_shape.BoundBox.ZMax)
            if (abs(shape.Volume - source_shape.Volume) > 1e-6
                    or any(abs(a - b) > 1e-6 for a, b in zip(bbox, source_bbox))):
                raise RuntimeError('invalid or mismatched assembly link: ' + link.Name)
            link_report.append({'name': link.Name, 'target': target.Name,
                                'volume_mm3': shape.Volume,
                                'bbox_mm': [shape.BoundBox.XMin, shape.BoundBox.XMax,
                                            shape.BoundBox.YMin, shape.BoundBox.YMax,
                                            shape.BoundBox.ZMin, shape.BoundBox.ZMax]})
        for obj in interim:
            shape = obj.Shape
            if shape.isNull() or not shape.isValid() or len(shape.Solids) != 1:
                raise RuntimeError('invalid interim shape: ' + obj.Name)
        if len(links) != 5 or len(interim) != 5:
            raise RuntimeError('unexpected assembly inventory')
        d.save()
        results.append({'kind': kind, 'file': d.FileName, 'links': link_report,
                        'interim_count': len(interim), 'saved': True})
        return
    bodies = [o for o in d.Objects if o.TypeId == 'PartDesign::Body' and getattr(o, 'Tip', None)]
    if not bodies:
        raise RuntimeError('no tipped PartDesign Body found')
    body_report = []
    for b in bodies:
        shape = b.Shape
        if not shape or shape.isNull() or not shape.isValid() or len(shape.Solids) < 1:
            raise RuntimeError('invalid Body shape: ' + b.Name)
        if 'Invalid' in getattr(b, 'State', []):
            raise RuntimeError('Body has Invalid state: ' + b.Name + ' ' + b.getStatusString())
        tip = b.Tip
        if 'Invalid' in getattr(tip, 'State', []):
            raise RuntimeError('Tip has Invalid state: ' + tip.Name + ' ' + tip.getStatusString())
        body_report.append({'name': b.Name, 'tip': tip.Name, 'valid': bool(shape.isValid()),
                            'solids': len(shape.Solids), 'volume_mm3': shape.Volume,
                            'bbox_mm': [shape.BoundBox.XMin, shape.BoundBox.XMax,
                                        shape.BoundBox.YMin, shape.BoundBox.YMax,
                                        shape.BoundBox.ZMin, shape.BoundBox.ZMax]})
    for o in d.Objects:
        engine = getattr(o, 'ExpressionEngine', [])
        if engine:
            status = o.getStatusString()
            if status != 'Valid':
                raise RuntimeError('unresolved expression on %s: %s' % (o.Name, status))
    d.save()
    results.append({'kind': kind, 'file': d.FileName, 'bodies': body_report,
                    'refreshed_external_expressions': refreshed_external_expressions,
                    'saved': True})

try:
    master_path = os.path.join(CFG['root'], 'hardware', 'freecad', 'pendant-master.FCStd')
    if not os.path.isfile(master_path):
        raise RuntimeError('missing master document: ' + master_path)
    master = open_doc(master_path)
    master.recompute()
    results.append({'kind': 'master', 'file': master.FileName,
                    'sheets': [o.Name for o in master.Objects if o.TypeId == 'Spreadsheet::Sheet'],
                    'saved': False})
    component_dir = os.path.join(CFG['root'], 'hardware', 'freecad', 'pendant-bodies')
    components = [os.path.join(component_dir, f) for f in CFG['components']]
    missing = [path for path in components if not os.path.isfile(path)]
    if missing:
        raise RuntimeError('missing canonical component documents: ' + ', '.join(missing))
    for path in components:
        validate_and_save(path, 'component')
    if CFG.get('assembly'):
        validate_and_save(CFG['assembly'], 'assembly-candidate')
except Exception as exc:
    errors.append(str(exc))
    errors.append(traceback.format_exc())
finally:
    for name in reversed(opened):
        try:
            App.closeDocument(name)
        except Exception:
            pass
    print('MODULAR_UPDATE_RESULT=' + json.dumps({'ok': not errors, 'results': results, 'errors': errors}))
'''.replace('@@CFG@@', repr(cfg))


def terminate_process_group(proc: subprocess.Popen[str]) -> None:
    if proc.poll() is not None:
        return
    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except ProcessLookupError:
        return
    try:
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        proc.wait(timeout=5)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assembly', type=Path, help='optional assembly candidate .FCStd to refresh after components')
    parser.add_argument('--freecadcmd', help='path to FreeCAD command-line executable')
    parser.add_argument('--timeout', type=int, default=170, help='worker timeout in seconds (maximum: 180; default: 170)')
    args = parser.parse_args()
    if not 1 <= args.timeout <= 180:
        parser.error('--timeout must be between 1 and 180 seconds')
    assembly = args.assembly.resolve() if args.assembly else None
    if assembly and not assembly.is_file():
        parser.error(f'assembly candidate does not exist: {assembly}')
    command = find_freecadcmd(args.freecadcmd)
    with tempfile.TemporaryDirectory(prefix='pendant-freecad-update-') as td:
        macro = Path(td) / 'update_modular_project.FCMacro'
        macro.write_text(make_macro(ROOT, assembly), encoding='utf-8')
        proc = subprocess.Popen([command, str(macro)], cwd=ROOT, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, text=True, start_new_session=True)
        try:
            output, _ = proc.communicate(timeout=args.timeout)
        except subprocess.TimeoutExpired:
            terminate_process_group(proc)
            output, _ = proc.communicate()
            print(output, end='')
            print(f'FreeCAD worker exceeded {args.timeout}s and was terminated')
            return 124
        print(output, end='')
        if proc.returncode != 0:
            return proc.returncode or 1
        marker = next((line.split('MODULAR_UPDATE_RESULT=', 1)[1]
                       for line in output.splitlines() if 'MODULAR_UPDATE_RESULT=' in line), None)
        if marker is None:
            print('FreeCAD exited without a structured validation result')
            return 1
        result = json.loads(marker)
        print(json.dumps(result, indent=2))
        return 0 if result.get('ok') else 1


if __name__ == '__main__':
    raise SystemExit(main())
