#!/usr/bin/env python3
"""Rasterize small Latin UI fonts as compact BDF assets for CircuitPython.

Requires Pillow. Font sources are the DejaVu Sans 2.37 TTF files; see the
accompanying license in fonts/DejaVu-LICENSE.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


CODEPOINTS = tuple(range(32, 127)) + tuple(range(160, 256)) + (0x2014, 0x2026)


def rasterize(font, codepoint):
    character = chr(codepoint)
    left, top, right, bottom = font.getbbox(character)
    width, height = max(0, right - left), max(0, bottom - top)
    advance = max(0, round(font.getlength(character)))
    image = Image.new("1", (max(1, width), max(1, height)), 0)
    if width and height:
        ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=1)
    rows = []
    for y in range(height):
        bits = 0
        for x in range(width):
            if image.getpixel((x, y)):
                bits |= 1 << (width - 1 - x)
        padding = (-width) % 8
        bits <<= padding
        rows.append("".join("%02X" % ((bits >> shift) & 0xFF)
                            for shift in range(((width + padding + 7) // 8 - 1) * 8,
                                               -1, -8)))
    return left, top, right, bottom, width, height, advance, rows


def make_bdf(source, size, output):
    font = ImageFont.truetype(str(source), size)
    ascent, descent = font.getmetrics()
    glyphs = [(codepoint, rasterize(font, codepoint))
              for codepoint in CODEPOINTS]
    max_width = max(glyph[1][4] for glyph in glyphs)
    max_height = max(glyph[1][5] for glyph in glyphs)
    x_offset = min(glyph[1][0] for glyph in glyphs)
    y_offset = min(ascent - glyph[1][3] for glyph in glyphs)
    family = Path(source).stem.replace(" ", "-")
    lines = [
        "STARTFONT 2.1",
        "COMMENT Generated by tools/generate_display_fonts.py",
        "COMMENT Source: DejaVu Sans 2.37",
        "FONT -DejaVu-{}-R-Normal--{}-140-75-75-P-{}-ISO10646-1".format(
            family, size, size * 5),
        "SIZE {} 75 75".format(size),
        "FONTBOUNDINGBOX {} {} {} {}".format(
            max_width, max_height, x_offset, y_offset),
        "STARTPROPERTIES 2",
        "FONT_ASCENT {}".format(ascent),
        "FONT_DESCENT {}".format(descent),
        "ENDPROPERTIES",
        "CHARS {}".format(len(glyphs)),
    ]
    for codepoint, glyph in glyphs:
        left, top, right, bottom, width, height, advance, rows = glyph
        lines.extend((
            "STARTCHAR U+{:04X}".format(codepoint),
            "ENCODING {}".format(codepoint),
            "SWIDTH {} 0".format(round(advance * 1000 / size)),
            "DWIDTH {} 0".format(advance),
            "BBX {} {} {} {}".format(width, height, left, ascent - bottom),
            "BITMAP",
        ))
        lines.extend(rows)
        lines.append("ENDCHAR")
    lines.append("ENDFONT")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--regular", type=Path, required=True)
    parser.add_argument("--bold", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("fonts"))
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    make_bdf(args.regular, 10, args.output_dir / "DejaVuSans-10.bdf")
    make_bdf(args.regular, 12, args.output_dir / "DejaVuSans-12.bdf")
    make_bdf(args.bold, 14, args.output_dir / "DejaVuSans-Bold-14.bdf")
    make_bdf(args.bold, 24, args.output_dir / "DejaVuSans-Bold-24.bdf")


if __name__ == "__main__":
    main()
